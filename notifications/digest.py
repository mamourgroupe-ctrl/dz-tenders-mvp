"""digest.py - Daily HTML digest builder."""

from datetime import date
from html import escape


def _priority(score):
    """Map relevance_score to P1/P2/P3."""
    if score >= 85:
        return "P1"
    if score >= 70:
        return "P2"
    if score >= 50:
        return "P3"
    return "P4"


def _group_by_priority(tenders):
    """Group tenders by priority tier."""
    groups = {"P1": [], "P2": [], "P3": [], "P4": []}
    for t in tenders:
        score = t.get("relevance_score", 0) or 0
        groups[_priority(score)].append(t)
    return groups


def _render_row(t):
    """Render one tender row as HTML."""
    title = escape(t.get("title", "no title"))
    link = t.get("link", "#")
    org = escape(t.get("organisation") or "-")
    wilaya = escape(t.get("wilaya") or "-")
    deadline = escape(t.get("deadline") or "-")
    products = ", ".join(t.get("matched_products", [])) or "-"
    return (
        "<tr>"
        f'<td><a href="{link}">{title}</a></td>'
        f"<td>{org}</td>"
        f"<td>{wilaya}</td>"
        f"<td>{deadline}</td>"
        f"<td>{products}</td>"
        "</tr>"
    )


def build_digest_html(tenders, run_date=None):
    """Build a full HTML digest from tenders."""
    run_date = run_date or date.today()
    groups = _group_by_priority(tenders)

    total = len(tenders)
    p1 = len(groups["P1"])
    p2 = len(groups["P2"])
    p3 = len(groups["P3"])

    parts = []
    parts.append('<!DOCTYPE html><html dir="rtl" lang="ar"><head><meta charset="UTF-8">')
    parts.append(f"<title>DZ Tenders Digest {run_date}</title>")
    parts.append("<style>")
    parts.append("body{font-family:Tahoma,Arial,sans-serif;background:#f5f5f5;padding:20px;}")
    parts.append(
        ".container{max-width:900px;margin:auto;background:white;padding:20px;border-radius:8px;}"
    )
    parts.append("h1{color:#1a5490;border-bottom:3px solid #1a5490;padding-bottom:10px;}")
    parts.append("h2{color:#2c7fb8;margin-top:30px;}")
    parts.append(".stats{display:flex;gap:20px;margin:20px 0;}")
    parts.append(
        ".stat{background:#e8f4f8;padding:15px;border-radius:6px;text-align:center;flex:1;}"
    )
    parts.append(".stat-num{font-size:32px;font-weight:bold;color:#1a5490;}")
    parts.append("table{width:100%;border-collapse:collapse;margin-top:10px;}")
    parts.append("th{background:#1a5490;color:white;padding:10px;text-align:right;}")
    parts.append("td{padding:10px;border-bottom:1px solid #eee;}")
    parts.append("a{color:#1a5490;text-decoration:none;}")
    parts.append(".footer{margin-top:30px;color:#666;font-size:12px;text-align:center;}")
    parts.append("</style></head><body><div class='container'>")
    parts.append(f"<h1>Daily Digest - {run_date}</h1>")
    parts.append("<div class='stats'>")
    parts.append(f"<div class='stat'><div class='stat-num'>{total}</div><div>Total</div></div>")
    parts.append(f"<div class='stat'><div class='stat-num'>{p1}</div><div>P1</div></div>")
    parts.append(f"<div class='stat'><div class='stat-num'>{p2}</div><div>P2</div></div>")
    parts.append(f"<div class='stat'><div class='stat-num'>{p3}</div><div>P3</div></div>")
    parts.append("</div>")

    for tier, label in [("P1", "Priority 1"), ("P2", "Priority 2"), ("P3", "Priority 3")]:
        if not groups[tier]:
            continue
        parts.append(f"<h2>{label} ({len(groups[tier])})</h2>")
        parts.append(
            "<table><tr><th>Title</th><th>Org</th><th>Wilaya</th><th>Deadline</th><th>Products</th></tr>"
        )
        for t in groups[tier]:
            parts.append(_render_row(t))
        parts.append("</table>")

    parts.append(
        f"<div class='footer'>Generated by DZ-TENDERS-MVP - {total} tenders processed</div>"
    )
    parts.append("</div></body></html>")

    return "\n".join(parts)
